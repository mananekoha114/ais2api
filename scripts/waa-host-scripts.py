"""Write waa/src/host_scripts.hpp from AIStudio2API's Go sources.

The header holds the JavaScript constants of internal/waa/host.go and
runtime.go at the commit waa/third_party/aistudio2api/ was taken from, byte
for byte. A constant is a raw string literal, a double-quoted literal without
escapes, or a sum of those and other constants. Reads the sources only; never
runs them.

  python -I scripts/waa-host-scripts.py <checkout or copy> <commit> waa/src/host_scripts.hpp

<checkout or copy> holds internal/waa/host.go and internal/waa/runtime.go,
or waa/host.go and waa/runtime.go.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

# (C++ name, comment, Go file, Go constant)
SCRIPTS = [
    ('host_script', 'Installs Function.prototype.toString, the timers and the Firefox DOM in one realm.', 'host.go', 'hostJavaScript'),
    ('prompt_script', "Types into the page's prompt box as the page's worker does.", 'runtime.go', 'promptScript'),
    ('pointer_script', "Dispatches trusted mouse and focus events at the page's Run button, last turn and Rerun button through the host's mouseInput.", 'runtime.go', 'pointerScript'),
    ('clear_prompt_script', 'Empties the prompt box through the native setter, without events.', 'runtime.go', 'clearPromptScript'),
    ('helper_script', 'Builds arrays, snapshot options and result callbacks in the top realm.', 'runtime.go', 'helperScript'),
    ('recorder_script', "The timing callback and the four loggers the page's BotGuard wrapper passes to the initialisation function.", 'runtime.go', 'recorderScript'),
]


class Constants:
    def __init__(self, source: str, name: str):
        self.source, self.name, self.cache = source, name, {}

    def value(self, name: str) -> str:
        if name not in self.cache:
            match = re.search(r'^const ' + re.escape(name) + r' = ', self.source, re.M)
            if not match:
                sys.exit(f'{self.name}: missing constant {name}')
            self.cache[name] = self.expression(match.end(), name)
        return self.cache[name]

    def expression(self, at: int, name: str) -> str:
        text = self.source
        parts = []
        while True:
            if text.startswith('`', at):
                end = text.index('`', at + 1)
                parts.append(text[at + 1:end])
                at = end + 1
            elif text.startswith('"', at):
                end = text.index('"', at + 1)
                literal = text[at + 1:end]
                if '\\' in literal:
                    sys.exit(f'{self.name}: escaped literal in {name}')
                parts.append(literal)
                at = end + 1
            else:
                match = re.compile(r'[A-Za-z_]\w*').match(text, at)
                if not match:
                    sys.exit(f'{self.name}: cannot read {name} at offset {at}')
                parts.append(self.value(match.group(0)))
                at = match.end()
            # A sum goes on past a '+' and the line break after it.
            match = re.compile(r'[ \t]*\+\s*').match(text, at)
            if not match:
                return ''.join(parts)
            at = match.end()


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    root, commit, out = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
    if not re.fullmatch(r'[0-9a-f]{40}', commit):
        sys.exit('the commit must be a full 40-digit hash')
    waa = root / 'internal/waa' if (root / 'internal/waa').is_dir() else root / 'waa'
    files = {name: Constants((waa / name).read_text(encoding='utf-8'), name) for name in ('host.go', 'runtime.go')}
    lines = [
        '// Copyright (c) 2026 Mag1cFall',
        '// SPDX-License-Identifier: MIT',
        '//',
        '// The JavaScript constants of AIStudio2API internal/waa/host.go and runtime.go',
        '// at commit ' + commit + ', byte for byte.',
        '// Generated by scripts/waa-host-scripts.py; regenerate, do not edit.',
        '#pragma once',
        '#include <string_view>',
        '',
        'namespace ais2api::waa::scripts {',
    ]
    total = 0
    for name, comment, file, constant in SCRIPTS:
        text = files[file].value(constant)
        if ')js"' in text:
            sys.exit(f'delimiter clash in {name}')
        total += len(text)
        lines.append('// ' + comment)
        lines.append('inline constexpr std::string_view ' + name + ' = R"js(' + text + ')js";')
    lines.append('// The source name of host scripts: SpiderMonkey, as patched, keeps scripts of')
    lines.append('// this name out of stacks and caller lookups, like its self-hosted code.')
    lines.append('inline constexpr std::string_view host_script_name = "self-hosted";')
    lines.append('} // namespace ais2api::waa::scripts')
    out.write_bytes(('\n'.join(lines) + '\n').encode('utf-8'))
    print(f'wrote {out}: {total} bytes of script')


if __name__ == '__main__':
    main()
